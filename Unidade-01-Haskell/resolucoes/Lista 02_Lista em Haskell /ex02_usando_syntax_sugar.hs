--2. Use **syntax sugar** para criar:
--    - a lista de números de 1 a 20.
--    - a lista de números pares de 0 a 20.
--   - a lista de múltiplos de 3 de 0 a 30.


main = do 
    print [1..20]                    -- lista de números de 1 a 20
    print [0,2..20]                  -- lista de números pares de 0 a 20
    print [0,3..30]                  -- lista de múltiplos de 3 de 0 a 30
    
